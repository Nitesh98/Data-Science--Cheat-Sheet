"""Generate coverage_matrix.csv and coverage_matrix.md from coverage_data.py.

Final timestamps come from ../renders/timestamps.json (written by the master
assembly step: {"C01.7": 1234.5, ...} = seconds into the master video).
Sections without a rendered timestamp are marked "NOT RENDERED".
"""
import csv, json, os, sys
from collections import Counter

# usage: build_coverage.py [docs_dir]  (default: this Maths docs folder)
HERE = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from coverage_data import R, COLUMNS, CHAPTERS, UNITS

ts_path = os.path.join(HERE, "..", "renders", "timestamps.json")
timestamps = json.load(open(ts_path)) if os.path.exists(ts_path) else {}


def hms(sec):
    sec = int(round(sec))
    return f"{sec // 3600}:{sec % 3600 // 60:02d}:{sec % 60:02d}"


rows = []
for r in R:
    rid, unit, rtype, sub, pre, obj, form, vis, ex, rec, sec = r
    ts = hms(timestamps[sec]) if sec in timestamps else "NOT RENDERED"
    status = "transcribed-unverified" if rtype == "syllabus" else "prerequisite (not assessed)"
    rows.append([rid, f"{unit} {UNITS[unit]}", rtype, sub, pre, obj, form, vis, ex, rec,
                 f"{sec} ({CHAPTERS[sec.split('.')[0]][0]})", ts, status])

with open(os.path.join(HERE, "coverage_matrix.csv"), "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(COLUMNS)
    w.writerows(rows)

ids = [r[0] for r in R]
assert len(ids) == len(set(ids)), "duplicate ids"
for r in R:
    assert r[10].split(".")[0] in CHAPTERS, r

with open(os.path.join(HERE, "coverage_matrix.md"), "w") as f:
    f.write(f"# Syllabus coverage matrix — JEE (Main) 2026, Paper 1, {getattr(__import__('coverage_data'), 'SUBJECT', 'Mathematics')}\n\n")
    f.write("Generated by `build_coverage.py` — edit `coverage_data.py`, not this file.\n\n")
    f.write("Verification status `transcribed-unverified` = subtopic text not yet diffed "
            "against the official PDF (see `syllabus/SOURCE.md`).\n\n")
    c = Counter(r[1] for r in R if r[2] == "syllabus")
    f.write("| Unit | Atomic subtopics | Chapters |\n|---|---|---|\n")
    for u, name in UNITS.items():
        if u == "PRE":
            continue
        chs = sorted({r[10].split('.')[0] for r in R if r[1] == u})
        f.write(f"| {u} {name} | {c[u]} | {', '.join(chs)} |\n")
    f.write(f"\nTotal syllabus rows: {sum(c.values())}; prerequisite rows: "
            f"{sum(1 for r in R if r[2] == 'prerequisite')}.\n\n")
    f.write("## Teaching order ↔ official order\n\n| Chapter | Title | Story question | Units | Budget (min) |\n|---|---|---|---|---|\n")
    for k, (t, q, u, m) in CHAPTERS.items():
        f.write(f"| {k} | {t} | {q} | {u} | {m} |\n")
    f.write(f"\nPlanned total: {sum(v[3] for v in CHAPTERS.values())} min "
            "(budget only; real durations come from recorded narration).\n\n## Rows\n\n")
    f.write("| " + " | ".join(COLUMNS) + " |\n|" + "---|" * len(COLUMNS) + "\n")
    for row in rows:
        f.write("| " + " | ".join(str(x).replace("|", "\\|") for x in row) + " |\n")
print(f"{len(rows)} rows written; {len(timestamps)} timestamps known")
